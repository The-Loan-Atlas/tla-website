/**
 * shortcodes-page.php — the blog shortcode reference page.
 *
 * Included by wp-stub.php for the "shortcodes" view, after the real theme
 * functions.php has registered its shortcodes. `npm run preview:blog` writes
 * the output to mockups/blog/shortcodes.html (gitignored).
 *
 * Nothing here is hand-maintained per shortcode. For every registered
 * shortcode it reads the function's doc comment and takes:
 *   - the first paragraph as the description, and
 *   - every line that starts with "[<tag>" as a usage example, with the text
 *     after "->" as that example's caption.
 * Each example is then run through the shortcode's real function, so what you
 * see is what a post renders. To add a shortcode to this page, register it in
 * functions.php and list its usage lines in its doc comment.
 */

$tla_sc_items = array();
foreach ( $GLOBALS['tla_shortcodes'] as $tag => $cb ) {
	$fn   = new ReflectionFunction( $cb );
	$doc  = (string) $fn->getDocComment();
	$body = array();
	foreach ( preg_split( '/\R/', $doc ) as $line ) {
		$line = preg_replace( '#^\s*/\*\*\s?|^\s*\*/\s*$|^\s*\*\s?#', '', $line );
		$body[] = rtrim( $line );
	}

	// Description: the first non-empty paragraph.
	$desc = array();
	foreach ( $body as $line ) {
		if ( '' === trim( $line ) ) {
			if ( $desc ) {
				break;
			}
			continue;
		}
		$desc[] = trim( $line );
	}

	// Examples: lines that start with "[tag" (this shortcode's own tag only).
	$examples = array();
	$seen     = array();
	// An enclosing shortcode's example carries its content and [/tag] on the same line.
	$q        = preg_quote( $tag, '/' );
	$pattern  = '/^\s*(\[' . $q . '(?:\s[^\]]*)?\](?:.*\[\/' . $q . '\])?)\s*(?:->\s*(.*))?$/';
	foreach ( $body as $line ) {
		if ( preg_match( $pattern, $line, $m ) && ! isset( $seen[ $m[1] ] ) ) {
			$seen[ $m[1] ] = true;
			$examples[]    = array( 'code' => $m[1], 'caption' => trim( $m[2] ?? '' ) );
		}
	}

	$tla_sc_items[] = array(
		'tag'      => $tag,
		'id'       => 'sc-' . preg_replace( '/[^a-z0-9]+/', '-', strtolower( $tag ) ),
		'desc'     => implode( ' ', $desc ),
		'fn'       => $fn->getName(),
		'line'     => $fn->getStartLine(),
		'examples' => $examples,
	);
}

